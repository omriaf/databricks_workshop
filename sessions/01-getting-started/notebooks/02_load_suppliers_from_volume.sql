-- MAGIC %md
-- MAGIC ## Refresh the same table
-- MAGIC
-- MAGIC `read_files` reads the CSV, uses its header, and infers column types.
-- MAGIC `CREATE OR REPLACE TABLE` replaces the contents of the destination table.
-- MAGIC
-- MAGIC **Run one loading cell: the one generated by Genie Code or the prepared SQL below.**
-- MAGIC The source CSV remains in the Volume.

-- COMMAND ----------

CREATE OR REPLACE TABLE workspace.default.bakehouse_suppliers
USING DELTA
AS
SELECT *
FROM read_files(
  '/Volumes/workspace/default/upload_files/bakehouse_suppliers.csv',
  format => 'csv',
  header => true,
  inferColumnTypes => true,
  schemaEvolutionMode => 'none'
);

-- COMMAND ----------

-- MAGIC %md
-- MAGIC ## Still 27 suppliers
-- MAGIC
-- MAGIC The file contains **27 suppliers**. Both counts should be 27 after the load,
-- MAGIC including when you run it again: one row per supplier, with no duplicate supplier IDs.

-- COMMAND ----------

SELECT
  COUNT(*) AS supplier_rows,
  COUNT(DISTINCT supplierID) AS unique_suppliers
FROM workspace.default.bakehouse_suppliers;

